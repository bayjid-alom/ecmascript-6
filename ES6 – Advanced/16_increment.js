/**
Increment কী?
Increment মানে হলো কোনো value বা number বাড়ানো। Programming-এ সাধারণত কোনো variable-এর value ১ করে বাড়ানোকে increment বলা হয়।

// ++count → আগে increment → পরে use
// count++ → আগে use → পরে increment
**/



// Increment
let count = 5;
count++;
console.log(count++);  // 6    Next console-এর সময় বাড়বে
console.log(count);    // 7
console.log(++count);  // 8   আগে count বাড়বে।


let number = 10;
number++;
number++;
number++;
console.log(number); // 13




